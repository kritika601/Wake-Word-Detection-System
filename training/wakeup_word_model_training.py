# function to convert a WAV into a MFCC and keep every audio as 13 *32 shape
import librosa
import numpy as np

def extract_mfcc(file_path):
    audio, sr = librosa.load(file_path, sr=16000)

    mfcc = librosa.feature.mfcc(
        y=audio,
        sr=sr,
        n_mfcc=13
    )

    # Pad or truncate to 32 frames
    if mfcc.shape[1] < 32:
        pad_width = 32 - mfcc.shape[1]
        mfcc = np.pad(
            mfcc,
            pad_width=((0, 0), (0, pad_width)),
            mode='constant'
        )
    else:
        mfcc = mfcc[:, :32]

    return mfcc.astype(np.float32)

