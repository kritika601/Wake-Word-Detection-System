# generated files for qcc748 according to mean and std of model
import librosa
import numpy as np

sr = 16000
n_fft = 2048
n_mels = 128
n_mfcc = 13

# Mel filterbank: shape (128, 1025) — matches librosa's internal one
mel_fb = librosa.filters.mel(sr=sr, n_fft=n_fft, n_mels=n_mels, norm='slaney', htk=False)

# DCT-II orthonormal basis: shape (13, 128) — matches scipy.fftpack.dct(type=2, norm='ortho')
from scipy.fftpack import dct
dct_matrix = dct(np.eye(n_mels), type=2, norm='ortho', axis=0)[:n_mfcc, :]

def export_c_array(name, arr):
    flat = arr.flatten()
    with open(f"{name}.h", "w") as f:
        f.write(f"#ifndef {name.upper()}_H\n#define {name.upper()}_H\n\n")
        f.write(f"#define {name.upper()}_ROWS {arr.shape[0]}\n")
        f.write(f"#define {name.upper()}_COLS {arr.shape[1]}\n\n")
        f.write(f"static const float {name}[{flat.size}] = {{\n")
        for i, v in enumerate(flat):
            f.write(f"{v:.8e}f, ")
            if (i + 1) % 8 == 0:
                f.write("\n")
        f.write("\n};\n\n#endif\n")

export_c_array("mel_filterbank", mel_fb)   # ~524KB, goes in flash, fine
export_c_array("dct_matrix", dct_matrix)   # ~6.7KB

